function FeatureCard({
  feature,
  index,
}: {
  feature: typeof FEATURES[number];
  index: number;
}) {
  const ref = useRef<HTMLDivElement>(null);
  const isInView = useInView(ref, { once: true, margin: '-100px' });

  const Icon = FeatureIcons[feature.icon];

  return (
    <motion.div
      ref={ref}
      initial={{ opacity: 0, y: 30 }}
      animate={isInView ? { opacity: 1, y: 0 } : { opacity: 0, y: 30 }}
      transition={{ duration: 0.6, delay: index * 0.1, ease: [0.16, 1, 0.3, 1] }}
      className="group relative p-8 md:p-10 rounded-2xl bg-white border border-neutral-100 hover:border-sumire-200 hover:shadow-lg transition-all duration-500"
    >
      {/* Icon */}
      <div className="inline-flex items-center justify-center w-12 h-12 rounded-xl bg-sumire-50 text-sumire-600 mb-6 group-hover:bg-sumire-100 transition-colors duration-300">
        {Icon && <Icon className="w-6 h-6" />}
      </div>

      {/* Title */}
      <h3 className="text-lg md:text-xl font-semibold text-neutral-900 mb-3">
        {feature.title}
      </h3>

      {/* Description */}
      <p className="text-sm md:text-base text-neutral-600 leading-relaxed">
        {feature.description}
      </p>

      {/* Hover Accent */}
      <div className="absolute bottom-0 left-8 right-8 h-0.5 bg-gradient-to-r from-transparent via-sumire-300 to-transparent scale-x-0 group-hover:scale-x-100 transition-transform duration-500" />
    </motion.div>
  );
}

